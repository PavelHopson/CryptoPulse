import type { StrategyLabResult } from './strategyLab';

// Keep enough significant digits for low-priced assets; two decimals can turn a valid price into 0.00.
const number = (value: number) => Number(value.toPrecision(12)).toString();
const signed = (value: number) => `${value >= 0 ? '+' : ''}${number(value)}%`;

function csvCell(value: string | number | boolean): string {
  return `"${String(value).replace(/"/g, '""')}"`;
}

/** Build a human-readable, deterministic research report without secrets. */
export function strategyResultToMarkdown(result: StrategyLabResult): string {
  const gates = result.qualityGates
    .map((gate) => `- ${gate.passed ? '[x]' : '[ ]'} ${gate.label}: ${gate.detail}`)
    .join('\n');
  const regimes = result.regimes
    .map((regime) => `| ${regime.label} | ${regime.startDate} — ${regime.endDate} | ${signed(regime.strategyReturnPct)} | ${signed(regime.baselineReturnPct)} |`)
    .join('\n');
  const reviews = result.reviews.map((review) => `### ${review.role}\n${review.verdict}`).join('\n\n');

  return [
    '# CryptoPulse Strategy Lab report',
    '',
    '> Paper-only research artifact. This report is not investment advice and does not enable live execution.',
    '',
    `- Experiment: \`${result.receipt.experimentId}\``,
    `- Decision: **${result.decision}**`,
    `- Dataset: ${result.dataset.source} (\`${result.dataset.kind}\`)`,
    `- Range: ${result.dataset.startDate} — ${result.dataset.endDate} (${result.dataset.pointCount} points)`,
    `- Checksum: \`${result.dataset.checksum}\``,
    '',
    '## Configuration',
    '',
    `- Fast window: ${result.receipt.config.fastWindow}`,
    `- Slow window: ${result.receipt.config.slowWindow}`,
    `- Fee: ${result.receipt.config.feeBps} bps`,
    `- Slippage: ${result.receipt.config.slippageBps} bps`,
    `- Paper capital: ${result.receipt.config.initialCapital}`,
    '',
    '## Results',
    '',
    `- Net return: **${signed(result.netReturnPct)}**`,
    `- Buy and hold: **${signed(result.baseline.buyAndHoldReturnPct)}**`,
    `- Excess vs baseline: **${signed(result.baseline.excessReturnPct)}**`,
    `- Max drawdown: **-${number(result.maxDrawdownPct)}%**`,
    `- Win rate: **${number(result.winRatePct)}%**`,
    `- Trades: **${result.tradeCount}**`,
    `- Estimated costs: **${number(result.estimatedCosts)}**`,
    `- Monte Carlo: P10 ${signed(result.monteCarlo.p10ReturnPct)}, median ${signed(result.monteCarlo.medianReturnPct)}, P90 ${signed(result.monteCarlo.p90ReturnPct)} (${result.monteCarlo.simulations} runs)`,
    `- Walk-forward: train ${signed(result.walkForward.trainReturnPct)}, test ${signed(result.walkForward.testReturnPct)}`,
    '',
    '## Quality gates',
    '',
    gates,
    '',
    '## Regimes',
    '',
    '| Period | Range | Strategy | Buy and hold |',
    '| --- | --- | ---: | ---: |',
    regimes,
    '',
    '## Independent review',
    '',
    reviews,
    '',
    'Generated by CryptoPulse Strategy Lab.',
    '',
  ].join('\n');
}

/** Export every paper trade as an Excel-compatible UTF-8 CSV. */
export function strategyTradesToCsv(result: StrategyLabResult): string {
  const rows = result.trades.map((trade) => [
    trade.entryDate,
    trade.exitDate,
    number(trade.entryPrice),
    number(trade.exitPrice),
    number(trade.netReturnPct),
  ]);
  const header = ['Entry date', 'Exit date', 'Entry price', 'Exit price', 'Net return %'];
  return '\uFEFF' + [header, ...rows].map((row) => row.map((cell) => csvCell(cell)).join(',')).join('\n') + '\n';
}
